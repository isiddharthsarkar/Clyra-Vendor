# vendor-port.mk
# --------------------------------------------------------------------------- #
def gen_vendor_port_mk(root: Path, targets: dict) -> str:
    primary = targets["primary"]
    codes = " ".join(t["codename"] for t in targets["targets"])
    lines = _header(targets, "#")
    lines += [
        "# Drop-in entry point for a ROM tree. In the device tree:",
        "#",
        "#     $(call inherit-product, vendor/clyra/ruan-in-16.0/vendor-port.mk)",
        "#",
        "# It is intentionally device-agnostic: whatever codename the ROM is",
        "# being ported to (ruan / garnet / organ / flute) resolves here, so a",
        "# port needs no edits to this file.",
        "",
        f"ifneq ($(filter {codes},$(TARGET_DEVICE)),)",
        "",
        "# Validate the path BEFORE using it, otherwise an unset variable turns",
        "# into a confusing 'No such file' from include rather than this message.",
        "#   CLYRA_VENDOR_PATH := vendor/clyra/ruan-in-16.0",
        "ifeq ($(CLYRA_VENDOR_PATH),)",
        "$(error Clyra: set CLYRA_VENDOR_PATH before inheriting vendor-port.mk)",
        "endif",
        "",
        "PRODUCT_SOONG_NAMESPACES += \\",
        "    $(CLYRA_VENDOR_PATH)/proprietary",
        "",
        "include $(CLYRA_VENDOR_PATH)/vendor.mk",
        "",
        "PRODUCT_PACKAGES += \\",
        "    rfs_symlinks",
        "",
        "# 64-bit only.",
        "TARGET_SUPPORTS_32_BIT_APPS := false",
        "TARGET_SUPPORTS_64_BIT_APPS := true",
        "",
        "# Everything below is what differs between SM7435 devices. A port can",
        "# override any of these before inheriting this file.",
        "CLYRA_DEVICE_CODENAME := $(TARGET_DEVICE)",
        f"CLYRA_BLOB_SOURCE := {primary['codename']}",
        "",
        "endif",
        "",
    ]
    return "\n".join(lines)


# --------------------------------------------------------------------------- #
GENERATORS = {
    "vendor.mk": gen_vendor_mk,
    "Android.mk": gen_android_mk,
    "Android.bp": gen_android_bp,
    "BoardConfigVendor.mk": gen_boardconfig,
    "vendor-port.mk": gen_vendor_port_mk,
}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero if generated output differs from disk")
    args = ap.parse_args()

    root = args.root.resolve()
    targets = load_targets(root)

    drift = []
    for name, fn in GENERATORS.items():
        content = fn(root, targets)
        dest = root / name
        if args.check:
            existing = dest.read_text(encoding="utf-8") if dest.is_file() else ""
            if existing != content:
                drift.append(name)
        else:
            dest.write_text(content, encoding="utf-8")
            print(f"wrote {name}")

    if args.check:
        if drift:
            print("out of date: " + ", ".join(drift), file=sys.stderr)
            print("run scripts/generate_build_files.py", file=sys.stderr)
            return 1
        print("all generated build files are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
