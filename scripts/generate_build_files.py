# --------------------------------------------------------------------------- #
def gen_boardconfig(root: Path, targets: dict) -> str:
    primary = targets["primary"]
    kernel = targets.get("kernel", {})
    dlkm = "proprietary/vendor_dlkm/lib/modules"
    lines = _header(targets, "#")
    lines += [
        f'TARGET_BOARD_PLATFORM := {targets["platform"]}',
        f'TARGET_BOARD_COMMON_PLATFORM := {targets["platform"]}',
        f'TARGET_BOOTLOADER_BOARD_NAME := {primary["codename"]}',
        "",
        "# 64-bit only. There is no secondary architecture: no lib/, no 32-bit",
        "# zygote, no 32-bit linker. Every userspace ELF in proprietary/ is",
        "# AArch64 — enforced by scripts/tests/check_arch.py.",
        "TARGET_ARCH := arm64",
        "TARGET_ARCH_VARIANT := armv8-a",
        "TARGET_CPU_ABI := arm64-v8a",
        "TARGET_CPU_ABI2 := ",
        "TARGET_CPU_VARIANT := generic",
        "TARGET_CPU_VARIANT_RUNTIME := cortex-a78",
        "# Empty on purpose: this stops the build system from ever placing a",
        "# 32-bit library into the vendor image.",
        "TARGET_2ND_ARCH :=",
        "TARGET_2ND_ARCH_VARIANT :=",
        "TARGET_2ND_CPU_ABI :=",
        "TARGET_2ND_CPU_ABI2 :=",
        "TARGET_2ND_CPU_VARIANT :=",
        "TARGET_USES_64_BIT_BINDER := true",
        "TARGET_SUPPORTS_32_BIT_APPS := false",
        "TARGET_SUPPORTS_64_BIT_APPS := true",
        f'TARGET_CPU_ABILIST := {targets["android_abi"]}',
        "TARGET_CPU_ABILIST64 := arm64-v8a",
        "# Deliberately empty: nothing in this tree is 32-bit.",
        "TARGET_CPU_ABILIST32 :=",
        "",
        "# Cross-port targets, from firmware/targets.json",
    ]
    for t in targets["targets"]:
        note = t.get("notes", "")
        lines.append(f"#   {t['codename']:<8} {t['device_name']} ({t['form_factor']})"
                     + (f" — {note}" if note else ""))
    alts = ",".join(t["codename"] for t in targets["targets"] if t["codename"] != primary["codename"])
    lines += [
        f"TARGET_DEVICE_ALT := {alts}",
        f"TARGET_BOARD_TYPE := {primary['form_factor']}",
        "",
        "# Partition targets",
        "TARGET_COPY_OUT_VENDOR := vendor",
        "TARGET_COPY_OUT_ODM := odm",
        "TARGET_COPY_OUT_VENDOR_DLKM := vendor_dlkm",
        "",
        "# Kernel (GKI)",
        "TARGET_KERNEL_ARCH := arm64",
        f'TARGET_KERNEL_SOURCE ?= kernel/xiaomi/{primary["codename"]}',
        "TARGET_KERNEL_CONFIG ?= " + " ".join(
            ["gki_defconfig", *kernel.get("config_fragments", [])]
        ),
        "BOARD_KERNEL_PAGESIZE := 4096",
        "BOARD_BOOT_HEADER_VERSION := 4",
        "",
        "# Kernel modules / DLKM",
        "#",
        "# Paths are relative to the repository root, where the blobs actually",
        "# live (`proprietary/...`). They previously pointed at",
        "# `vendor/ruan/proprietary/...`, which does not exist, so `$(wildcard)`",
        "# silently expanded to nothing and none of the modules were ever",
        "# staged. The ordered LOAD list comes from the vendor's own",
        "# modules.load so hard dependencies are satisfied.",
        f"CLYRA_DLKM_DIR := {dlkm}",
        "CLYRA_DLKM_MODULES := $(sort $(wildcard $(CLYRA_DLKM_DIR)/*.ko))",
        "CLYRA_DLKM_LOAD := $(addprefix $(CLYRA_DLKM_DIR)/,$(shell sed -e 's/#.*//' "
        "-e '/^[[:space:]]*$$/d' $(CLYRA_DLKM_DIR)/modules.load 2>/dev/null))",
        "",
        "BOARD_VENDOR_KERNEL_MODULES := $(CLYRA_DLKM_MODULES)",
        "BOARD_VENDOR_KERNEL_MODULES_LOAD := $(CLYRA_DLKM_LOAD)",
        "BOARD_VENDOR_RAMDISK_KERNEL_MODULES_LOAD := $(CLYRA_DLKM_LOAD)",
        "",
        "# Parity guard: a modules.load entry with no matching .ko leaves the",
        "# signing step with nothing to sign. Fail loudly rather than ship a",
        "# half-loaded module set.",
        "ifeq ($(wildcard $(CLYRA_DLKM_DIR)),)",
        "$(warning Clyra: $(CLYRA_DLKM_DIR) missing -- kernel modules not staged)",
        "else",
        "_CLYRA_DLKM_MISSING := $(filter-out $(CLYRA_DLKM_MODULES),$(CLYRA_DLKM_LOAD))",
        "ifneq ($(_CLYRA_DLKM_MISSING),)",
        "$(error Clyra: modules.load references missing .ko files: $(_CLYRA_DLKM_MISSING))",
        "endif",
        "endif",
        "",
        "# WLAN firmware directory (board dependent; set per target if it differs)",
        "CLYRA_WLAN_FW_DIR ?= qca6750",
        "",
        "# Platform flags",
        "BOARD_USES_QCOM_HARDWARE := true",
        "TARGET_USES_QCOM_BSP := true",
        "BOARD_VNDK_VERSION := current",
        "BOARD_API_LEVEL := 36",
        "BOARD_SHIPPING_API_LEVEL := 36",
        "PRODUCT_SHIPPING_API_LEVEL := 36",
        "",
        "# Display & graphics (Adreno 710 / Vulkan 1.3)",
        "BOARD_USES_ADRENO := true",
        "TARGET_USES_ION := true",
        "TARGET_USES_GRALLOC4 := true",
        "TARGET_USES_HWC2 := true",
        "TARGET_USES_VULKAN := true",
        "",
        "# Audio (CAF PAL / AGM)",
        "BOARD_USES_ALSA_AUDIO := true",
        "AUDIO_FEATURE_ENABLED_GKI := true",
        "AUDIO_FEATURE_ENABLED_DLKM := true",
        "",
        "# Connectivity",
        "BOARD_HAVE_BLUETOOTH_QCOM := true",
        "WIFI_HIDL_FEATURE_DUAL_INTERFACE := true",
        "",
        "# Set by the ROM tree; overridable per port.",
        "TARGET_KERNEL_VERSION ?= " + kernel.get("version", "6.6"),
        "TARGET_LINUX_KERNEL_VERSION ?= " + kernel.get("version", "6.6"),
        "",
    ]
    return "\n".join(lines)


