#!/usr/bin/env python3
"""Generate the build integration files for every cross-port target.

Produces, from `firmware/targets.json`:

    Android.mk            RFS / WLAN symlink setup, guarded per codename
    Android.bp            CAF soong namespaces
    BoardConfigVendor.mk  board-level knobs, arch, kernel module staging
    vendor.mk             PRODUCT_COPY_FILES (regenerated from proprietary/)
    vendor-port.mk        thin per-device entry point for a ROM tree

Everything is derived from data, so adding a new SM7435 device is a one-line
change in targets.json rather than a hunt through four hand-edited makefiles.

Usage:
    generate_build_files.py [--root .] [--check]

`--check` exits non-zero if the files on disk differ from what would be
generated, which is what CI and the self-test use.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

SKIP_DIRS = {"lost+found"}

# partition directory -> TARGET_COPY_OUT_* suffix
PARTITIONS = {
    "vendor": "VENDOR",
    "vendor_dlkm": "VENDOR_DLKM",
    "odm": "ODM",
    "odm_dlkm": "ODM_DLKM",
    "system_dlkm": "SYSTEM_DLKM",
    "my_product": "PRODUCT",
    "my_heytap": "PRODUCT",
    "my_manifest": "PRODUCT",
}

# Paths inside a partition that are never copied to the target.
# `etc/*.prop` files under vendor_dlkm/odm_dlkm are module metadata only.
SKIP_PARTITION_ETC = {"my_manifest"}


def load_targets(root: Path) -> dict:
    path = root / "firmware" / "targets.json"
    if not path.is_file():
        raise SystemExit(f"missing {path}")
    return json.loads(path.read_text(encoding="utf-8"))


def _q(text: str) -> str:
    """Escape a path for a make rule."""
    return text.replace("$", "$$").replace(" ", r"\ ")


def _join_continuations(text: str) -> list[str]:
    out, buf = [], ""
    for line in text.splitlines():
        if line.rstrip().endswith("\\"):
            buf += line.rstrip()[:-1]
        else:
            out.append(buf + line)
            buf = ""
    if buf:
        out.append(buf)
    return out


def _header(targets: dict, comment: str) -> list[str]:
    primary = targets["primary"]
    codes = ", ".join(t["codename"] for t in targets["targets"])
    return [
        f"{comment} Automatically generated by Clyra-Vendor — do not edit.",
        f"{comment} Source: {primary['device_name']} ({primary['codename']}), "
        f"{targets['soc']} / {targets['platform']}",
        f"{comment} Cross-port targets: {codes}",
        f"{comment} Regenerate with scripts/generate_build_files.py",
        f"{comment} ABI: {targets['android_abi']} (64-bit only)",
        "",
    ]


# --------------------------------------------------------------------------- #
# vendor.mk
# --------------------------------------------------------------------------- #
def gen_vendor_mk(root: Path, targets: dict) -> str:
    staging = root / "proprietary"
    if not staging.is_dir():
        raise SystemExit(f"missing {staging}")

    entries: dict[str, list[str]] = {}
    empty: list[str] = []

    for dirpath, dirnames, filenames in os.walk(staging):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        for name in sorted(filenames):
            src = Path(dirpath) / name
            if not src.is_symlink() and not src.exists():
                continue
            if not src.is_symlink() and src.stat().st_size == 0:
                empty.append(src.relative_to(staging).as_posix())

            rel = src.relative_to(staging)
            top = rel.parts[0]
            if top not in PARTITIONS:
                continue
            inner = Path(*rel.parts[1:])
            if not inner.parts:
                continue
            if top in SKIP_PARTITION_ETC and inner.parts[0] == "etc":
                continue

            out_var = f"TARGET_COPY_OUT_{PARTITIONS[top]}"
            try:
                src_rel = src.relative_to(root).as_posix()
            except ValueError:
                src_rel = rel.as_posix()
            entries.setdefault(out_var, []).append(
                f"    {_q(src_rel)}:$({out_var})/{_q(inner.as_posix())}"
            )

    lines = _header(targets, "#")
    lines += [
        "# Blobs are committed at <repo-root>/proprietary/ and copied into the",
        "# image of the partition named by the first path component.",
        "",
        "PRODUCT_SOONG_NAMESPACES += \\",
        "    proprietary",
        "",
    ]

    for out_var in sorted(entries):
        lines.append("PRODUCT_COPY_FILES += \\")
        lines.append(" \\\n".join(entries[out_var]))
        lines.append("")

    if not entries:
        lines.append("# No blobs matched a known partition; nothing to copy.")
        lines.append("")

    if empty:
        lines += [
            "# WARNING: these blobs are 0 bytes and will be copied as-is.",
            "# They are almost certainly a truncated extraction; re-run",
            "# scripts/extract-vendor.sh and verify with",
            "# scripts/tests/check_blobs.py . --strict",
        ]
        lines += [f"#   0-byte: {e}" for e in empty[:40]]
        if len(empty) > 40:
            lines.append(f"#   ... and {len(empty) - 40} more")
        lines.append("")

    if entries:
        lines.append("# Partition output variables used above")
        for out_var in sorted(entries):
            lines.append(f"{out_var} := {out_var.removeprefix('TARGET_COPY_OUT_').lower()}")
        lines.append("")

    return "\n".join(lines)


