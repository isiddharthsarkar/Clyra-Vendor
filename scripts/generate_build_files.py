def gen_android_mk(root: Path, targets: dict) -> str:
    codes = " ".join(t["codename"] for t in targets["targets"])
    lines = _header(targets, "#")
    lines += [
        f"# Only build this package for the supported SM7435 devices. The list",
        f"# lives in firmware/targets.json; add a codename there, not here.",
        "",
        "LOCAL_PATH := $(call my-dir)",
        "",
        f"ifneq ($(filter {codes},$(TARGET_DEVICE)),)",
        "",
        "include $(CLEAR_VARS)",
        "LOCAL_MODULE := rfs_symlinks",
        "LOCAL_MODULE_CLASS := FAKE",
        "LOCAL_MODULE_TAGS := optional",
        "LOCAL_MODULE_OWNER := xiaomi",
        "",
        "RFS_SUBSYSTEMS := \\",
    ]
    for i, sub in enumerate(RFS_SUBSYSTEMS):
        sep = " \\" if i < len(RFS_SUBSYSTEMS) - 1 else ""
        lines.append(f"    {sub}{sep}")
    lines += ["", "RFS_TARGET := $(TARGET_OUT_VENDOR)/rfs", "", "$(RFS_TARGET):"]

    for sub in RFS_SUBSYSTEMS:
        lines += [
            f"\t$(hide) mkdir -p $(RFS_TARGET)/{sub}/readonly/vendor",
            f"\t$(hide) ln -sf /mnt/vendor/persist/hlos_rfs/shared $(RFS_TARGET)/{sub}/hlos",
            f"\t$(hide) ln -sf /mnt/vendor/persist/rfs/shared $(RFS_TARGET)/{sub}/shared",
            f"\t$(hide) ln -sf /mnt/vendor/persist/rfs/{sub} $(RFS_TARGET)/{sub}/readwrite",
            f"\t$(hide) ln -sf /vendor/firmware $(RFS_TARGET)/{sub}/readonly/vendor/firmware",
            f"\t$(hide) ln -sf /vendor/firmware_mnt $(RFS_TARGET)/{sub}/readonly/firmware",
        ]
    lines.append("")
    for link, dest in RFS_LINKS:
        lines.append(f"\t$(hide) ln -sf {dest} $(RFS_TARGET)/{link}")

    lines += [
        "",
        "# WLAN MAC / firmware links. The qca_cld firmware directory name differs",
        "# per board, so it is taken from the target data instead of hardcoded.",
        "\t$(hide) mkdir -p $(TARGET_OUT_VENDOR)/firmware/wlan/qca_cld/$(CLYRA_WLAN_FW_DIR)",
        "\t$(hide) ln -sf /mnt/vendor/persist/wlan/wlan_mac.bin \\",
        "\t\t$(TARGET_OUT_VENDOR)/firmware/wlan/qca_cld/$(CLYRA_WLAN_FW_DIR)/wlan_mac.bin",
        "\t$(hide) ln -sf /data/vendor/firmware/wlanmdsp.mbn \\",
        "\t\t$(TARGET_OUT_VENDOR)/firmware/wlanmdsp.otaupdate",
        "",
        "LOCAL_POST_INSTALL_CMD := $(RFS_TARGET)",
        "include $(BUILD_PHONY_PACKAGE)",
        "",
        "endif",
        "",
    ]
    return "\n".join(lines)


